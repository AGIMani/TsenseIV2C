import {chromium} from "@playwright/test";
import {mkdir} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import assert from "node:assert/strict";
const out=fileURLToPath(new URL("../../../logs/joint_enable_validation/",import.meta.url));
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||"C:/Program Files/Google/Chrome/Application/chrome.exe"});
const page=await browser.newPage({ignoreHTTPSErrors:process.env.TEST_IGNORE_TLS==="1",viewport:{width:1440,height:1050}}),errors=[];
page.on("pageerror",e=>errors.push(e.message));
const ready=()=>page.waitForFunction(()=>!document.querySelector("#start").disabled);
const joint=n=>page.locator(`input[data-joint="${n}"]`);
try{
  await page.goto((process.env.WEB_URL||"http://127.0.0.1:8771")+"/?model=TsenseI_v3_0");await ready();
  assert.equal(await page.locator("#joint-enable-groups input").count(),20);
  await joint("left_hand_index_DIP_joint").uncheck();
  assert.match(await page.locator("#joint-enable-count").innerText(),/17 \/ 18/);
  assert(await joint("left_hand_thumb_rotaback_joint2").isDisabled());
  await page.locator("#side").selectOption("right");await ready();
  assert(await joint("right_hand_index_DIP_joint").isChecked());
  await page.locator("#disable-all-joints").click();
  assert.equal(await page.locator("#joint-enable-groups input:checked").count(),2);
  await page.locator("#enable-all-joints").click();
  assert.equal(await page.locator("#joint-enable-groups input:checked").count(),20);
  await page.locator("#side").selectOption("left");await ready();
  assert.equal(await joint("left_hand_index_DIP_joint").isChecked(),false);
  await page.locator("#hand-model").selectOption("TsenseI_v2");await ready();
  assert.equal(await page.locator("#joint-enable-groups input").count(),21);
  assert(await joint("left_hand_index_DIP_joint").isChecked());
  await joint("left_hand_thumb_swing_joint").uncheck();
  await page.locator("#hand-model").selectOption("TsenseI_v3_2");await ready();
  assert.equal(await page.locator("#joint-enable-groups input").count(),20);
  assert.match(await page.locator("#joint-enable-note").innerText(),/尚未接通下位机/);
  assert.equal(await page.locator("#joint-enable-groups input:enabled").count(),0);
  await page.locator("#hand-model").selectOption("TsenseI_v3_0");await ready();
  assert.equal(await joint("left_hand_index_DIP_joint").isChecked(),false);
  await page.screenshot({path:`${out}/desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${out}/mobile.png`,fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  console.log("Joint selector OK: all models, side/model isolation, bulk toggles, responsive layout");
}finally{await browser.close();}
