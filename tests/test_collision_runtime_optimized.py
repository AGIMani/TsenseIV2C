@pytest.mark.parametrize("model", MODELS)
@pytest.mark.parametrize("side", ("left", "right"))
def test_kinematic_contact_distances_match_full_forward(model, side):
    profile = load_hand_profile(model)
    original = profile.create_collision_filter(side)
    fast = KinematicContactChecker(profile.create_collision_filter(side))
    rng = np.random.default_rng(7625)
    for _ in range(20):
        pose = {name: rng.uniform(lo, hi) for name, (lo, hi) in profile.joint_limits(side).items()}
        original.sync_pose_from_dict(pose)
        fast.sync_pose_from_dict(pose)
        expected = [(row["g1"], row["g2"], row["dist_mm"]) for row in original.contact_summary()]
        actual = [(row["g1"], row["g2"], row["dist_mm"]) for row in fast.contact_summary()]
        assert actual == expected


@pytest.mark.parametrize("model", MODELS)
def test_stop_cached_path_matches_full_dynamics_reference(model):
    profile = load_hand_profile(model)
    fast = StopCollisionGuard(profile, "left")
    reference = SelfCollisionGuard(
        physics_filter=profile.create_collision_filter("left"), strategy="stop",
        allowed_penetration_mm=0, path_step_rad=.025, max_path_steps=128,
        bisection_iterations=14,
    )
    current = profile.init_pose("left")
    rng = np.random.default_rng(6502)
    for _ in range(8):
        pose = {name: rng.uniform(lo, hi) for name, (lo, hi) in profile.joint_limits("left").items()}
        expected, info = reference.project(pose, current_values=current)
        actual = fast.project(pose)
        assert actual == expected
        assert fast.diagnostics["limited"] == info["limited"]
        assert fast.diagnostics["output_max_penetration_mm"] == info["output_max_penetration_mm"]
        current = actual
    assert fast.diagnostics["cache_hits"] > 0


@pytest.mark.parametrize("model", MODELS)
@pytest.mark.parametrize("side", ("left", "right"))
def test_pair_bounds_contain_compiled_vertices_and_prove_separation(model, side):
    guard = MinkCollisionGuard(load_hand_profile(model), side)
    bound = guard.bounds
    for geom in range(guard.model.ngeom):
        if guard.model.geom_type[geom] != mujoco.mjtGeom.mjGEOM_MESH:
            continue
        mid = guard.model.geom_dataid[geom]
        first = guard.model.mesh_vertadr[mid]
        vertices = guard.model.mesh_vert[first:first + guard.model.mesh_vertnum[mid]].astype(float)
        assert np.all(np.linalg.norm(vertices, axis=1) <= bound._radius[geom])
        assert np.all(np.abs(vertices - bound._local_center[geom]) <= bound._half_extent[geom])
    rng = np.random.default_rng(1129)
    for _ in range(40):
        q = rng.uniform(guard.lower, guard.upper)
        guard._update(q)
        lower = bound.lower_bounds(guard.configuration.data)
        # A contact generated by the separate collision pipeline may never have
        # a positive separating bound. This checks frames and bound orientation.
        mujoco.mj_collision(guard.model, guard.configuration.data)
        lookup = {tuple(sorted(pair)): i for i, pair in enumerate(guard.pairs)}
        for contact in guard.configuration.data.contact:
            key = tuple(sorted((int(contact.geom1), int(contact.geom2))))
            if key in lookup and contact.dist < 0:
                assert lower[lookup[key]] <= 0


def test_exact_cache_does_not_confuse_nearby_poses_or_keep_unbounded_history():
    guard = MinkCollisionGuard(load_hand_profile("TsenseI_v3_2_withid"), "left")
    pose = dict(zip(guard.names, guard.q))
    guard.project(pose)
    calls = guard._distance_queries
    guard.distances(pose)
    assert guard._distance_queries == calls
    changed = dict(pose)
    changed[guard.names[0]] += 1e-10
    guard.distances(changed)
    assert len(guard._distance_cache) == 2
    guard.project(pose)
    assert len(guard._distance_cache) == 1


