def test_stop_rebase_before_first_frame_and_exposed_state_after_cached_projection():
    profile = load_hand_profile("TsenseI_v3_0")
    guard = StopCollisionGuard(profile, "left", finger_stop=True)
    initial = profile.init_pose("left")
    guard.guard.rebase(initial)
    target = dict(initial)
    target["left_hand_ring_swing_joint"] = .695
    target["left_hand_pinky_swing_joint"] = .005
    output = guard.project(target)
    np.testing.assert_array_equal(guard.filter.data.qpos,
                                  [output[n] for n in guard.filter.names])
    assert all(row["pen_mm"] <= 1e-9 for row in guard.filter.contact_summary())
    guard.guard.reset()
    guard.guard.rebase(initial)
    assert guard.guard._previous_safe == initial


def test_degenerate_native_zero_is_repaired_only_with_independent_support_certificate():
    profile = load_hand_profile("TsenseI_v3_0")
    guard = MinkCollisionGuard(profile, "right")
    rng = np.random.default_rng(17)
    repairs = 0
    for _ in range(10):
        q = rng.uniform(guard.lower, guard.upper)
        guard._update(q)
        for index, (a, b) in enumerate(guard.pairs):
            witness = np.zeros(6)
            native = mujoco.mj_geomDistance(guard.model, guard.configuration.data, a, b, .05, witness)
            if native != 0:
                continue
            certificate = guard.bounds.witness_lower_bound(index, guard.configuration.data, witness)
            repaired = guard._query(index)
            assert repaired == certificate
            if certificate > 0:
                repairs += 1
                # The independent contact pipeline agrees that this pair does
                # not penetrate. No scalar zero is simply assumed erroneous.
                mujoco.mj_collision(guard.model, guard.configuration.data)
                assert not any({int(c.geom1), int(c.geom2)} == {a, b} and c.dist < 0
                               for c in guard.configuration.data.contact)
    if not repairs:
        pytest.skip("backend no longer produces a degenerate zero in the regression corpus")


def test_swept_thumb_index_collision_between_original_samples_is_rejected():
    guard = MinkCollisionGuard(load_hand_profile("TsenseI_v3_2"), "right")
    case = json.loads((ROOT / "tests/fixtures/a32_collision_swept_regression.json").read_text())
    start, end = np.array(case["qstart"]), np.array(case["qend"])
    assert guard._feasible(start) and guard._feasible(end)
    count = int(np.ceil(np.max(np.abs(end - start)) / .025))
    assert all(guard._feasible(start + (end - start) * (i / count)) for i in range(1, count))
    bad = start + (end - start) * .4
    guard._update(bad)
    mujoco.mj_collision(guard.model, guard.configuration.data)
    assert any(c.dist < -1e-6 for c in guard.configuration.data.contact)
    assert not guard._path_feasible(start, end)
    assert guard._path_refinements > 0


