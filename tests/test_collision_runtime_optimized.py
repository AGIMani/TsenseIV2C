def test_tiny_refinement_budget_fails_closed_and_cached_paths_do_not_spend_it_again():
    guard = MinkCollisionGuard(load_hand_profile("TsenseI_v3_2"), "right", max_path_refinements=1)
    case = json.loads((ROOT / "tests/fixtures/a32_collision_swept_regression.json").read_text())
    start, end = np.array(case["qstart"]), np.array(case["qend"])
    assert not guard._path_feasible(start, end)
    assert guard._path_budget_exhausted
    assert guard._path_refinements == 1
    assert not guard._path_feasible(start, end)
    assert guard._path_refinements == 1
    guard.q = start.copy()
    output = guard.project(dict(zip(guard.names, end)))
    assert guard.diagnostics["path_refinements"] <= 1
    assert guard.diagnostics["path_budget_exhausted"]
    assert guard.diagnostics["path_refinement_budget"] == 1
    assert all(guard.distances(output) >= guard.margins - 1e-7)
    for t in np.linspace(0, 1, 101):
        guard._update(start + (guard.q - start) * t)
        mujoco.mj_collision(guard.model, guard.configuration.data)
        assert not any(c.dist < -1e-6 for c in guard.configuration.data.contact)
